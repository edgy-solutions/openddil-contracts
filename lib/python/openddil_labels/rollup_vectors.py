"""Golden vectors for the class row (rollup marker) form: class_label, admits_class, split.

Status: Builds on the PROPOSED ADR-0055 §2a (#38) rollup marker, not a ruled form. No key is
written here; the key form for a marker row is owed.

The vectors are generated by code and written once to vectors/class_label.json
(python -m openddil_labels.rollup_vectors --write); a test regenerates them and
asserts byte equality.

Nothing calls this module yet.
"""

import json
import pathlib
import sys

from .admission import Refused
from .model import Declaration, Dimension
from .rollup import admits_class, class_label, split_by_audience

POLICY_ID = "example:policy-1"
NATIONS = ("ATL", "BDR", "CYR")
HOLDERS = ("H1", "H2")


def declaration_data():
    """The declaration the vectors use, as plain data."""
    return {
        "policy_id": POLICY_ID,
        "dimensions": [
            {
                "name": "nation",
                "type": "permissive",
                "vocabulary": list(NATIONS),
                "owner": "nation-steward",
                "has_author": True,
            },
            {
                "name": "data_rights_holder",
                "type": "restrictive",
                "vocabulary": list(HOLDERS),
                "owner": "rights-steward",
                "has_author": False,
            },
        ],
    }


def load_declaration(data):
    """Build a Declaration from declaration_data()'s shape."""
    makers = {
        "permissive": lambda d: Dimension.permissive(
            d["name"], d["vocabulary"], d["owner"], has_author=d["has_author"]
        ),
        "restrictive": lambda d: Dimension.restrictive(d["name"], d["vocabulary"], d["owner"]),
        "exclusionary": lambda d: Dimension.exclusionary(d["name"], d["vocabulary"], d["owner"]),
        "hierarchical": lambda d: Dimension.hierarchical(d["name"], d["vocabulary"], d["owner"]),
    }
    dims = tuple(makers[d["type"]](d) for d in data["dimensions"])
    return Declaration(data["policy_id"], dims)


def _lab(author, release, holders=("H1",)):
    return {"nation": {"author": author, "release": release}, "data_rights_holder": list(holders)}


def _marker(release, holders=("H1",), **extra):
    n = {"rollup": True, "release": release}
    n.update(extra)
    return {"nation": n, "data_rights_holder": list(holders)}


def _class_label_cases():
    return [
        ("single_author_with_release", _lab("ATL", ["BDR"])),
        ("single_author_no_release", _lab("ATL", None)),
        ("single_author_empty_release", _lab("ATL", [])),
        ("author_already_in_release", _lab("ATL", ["ATL", "CYR"])),
        ("null_label", None),
        ("invalid_label_out_of_vocabulary", _lab("ZZZ", [])),
        ("invalid_label_marker_form_is_not_a_label", _marker(["ATL"])),
        ("invalid_label_missing_dimension", {"nation": {"author": "ATL", "release": []}}),
    ]


def _admits_cases():
    nat = lambda *n: {"nation": list(n), "data_rights_holder": ["H1"]}  # noqa: E731
    return [
        ("rollup_viewer_holds_release_value", nat("BDR"), _marker(["ATL", "BDR"])),
        ("rollup_viewer_holds_none", nat("CYR"), _marker(["ATL", "BDR"])),
        ("rollup_viewer_holds_nothing", {"nation": [], "data_rights_holder": ["H1"]}, _marker(["ATL"])),
        ("rollup_empty_release_viewer_atl", nat("ATL"), _marker([])),
        ("rollup_empty_release_viewer_all", nat("ATL", "BDR", "CYR"), _marker([])),
        ("old_form_author_none", nat("ATL"), _lab(None, ["ATL"])),
        ("empty_author_set_without_marker", nat("ATL"), {"nation": {"author": [], "release": ["ATL"]}, "data_rights_holder": ["H1"]}),
        ("marker_with_author", nat("ATL"), _marker(["ATL"], author="ATL")),
        ("marker_with_author_none", nat("ATL"), _marker(["ATL"], author=None)),
        ("marker_with_empty_author", nat("ATL"), _marker(["ATL"], author=[])),
        ("rollup_is_integer_one", nat("ATL"), _marker(["ATL"]) | {"nation": {"rollup": 1, "release": ["ATL"]}}),
        ("rollup_is_string_true", nat("ATL"), _marker(["ATL"]) | {"nation": {"rollup": "true", "release": ["ATL"]}}),
        ("rollup_is_false", nat("ATL"), _marker(["ATL"]) | {"nation": {"rollup": False, "release": ["ATL"]}}),
        ("rollup_missing", nat("ATL"), _marker(["ATL"]) | {"nation": {"release": ["ATL"]}}),
        ("rollup_no_release", nat("ATL"), _marker(["ATL"]) | {"nation": {"rollup": True}}),
        ("rollup_release_none", nat("ATL"), _marker(None)),
        ("restrictive_dimension_unmet", nat("ATL"), _marker(["ATL"], holders=("H1", "H2"))),
        ("restrictive_dimension_met", nat("ATL"), _marker(["ATL"], holders=("H1",))),
    ]


def _split_cases():
    return [
        (
            "rollup_over_one_author",
            [("c1", _lab("ATL", None)), ("c2", _lab("ATL", [])), ("c3", _lab("ATL", ["ATL"]))],
        ),
        (
            "two_authors_two_classes",
            [("a1", _lab("ATL", [])), ("a2", _lab("ATL", [])), ("b1", _lab("BDR", []))],
        ),
        (
            "mixed_with_withheld",
            [
                ("a1", _lab("ATL", ["BDR"])),
                ("b1", _lab("BDR", [])),
                ("u1", None),
                ("u2", _lab("ZZZ", [])),
                ("u3", {}),
                ("h1", _lab("ATL", [], holders=("H1", "H2"))),
            ],
        ),
    ]


def _plain(x):
    """A JSON-ready copy: tuples as lists, Refused as {reason, dimension, value}."""
    if isinstance(x, Refused):
        return {"reason": x.reason, "dimension": x.dimension, "value": x.value}
    if isinstance(x, dict):
        return {k: _plain(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_plain(v) for v in x]
    return x


def generate_class_vectors():
    data = declaration_data()
    decl = load_declaration(data)
    cl_out = []
    for name, label in _class_label_cases():
        r = class_label(label, decl)
        refused = isinstance(r, Refused)
        cl_out.append(
            {
                "name": name,
                "label": label,
                "class_label": None if refused else r,
                "refused": r.reason if refused else None,
            }
        )
    ad_out = []
    for name, viewer, row in _admits_cases():
        ad_out.append(
            {
                "name": name,
                "viewer": viewer,
                "class_label": row,
                "admitted": admits_class(viewer, row, decl),
            }
        )
    sp_out = []
    for name, contributors in _split_cases():
        s = split_by_audience(contributors, decl)
        sp_out.append(
            {
                "name": name,
                "contributors": [{"id": cid, "label": lab} for cid, lab in contributors],
                "classes": [{"label": c.label, "members": list(c.members)} for c in s.classes],
                "withheld": s.withheld,
                "withheld_by_reason": [[r, n] for r, n in s.withheld_by_reason],
            }
        )
    return {
        "declaration": data,
        "class_label": cl_out,
        "admits_class": ad_out,
        "split": sp_out,
    }


def vectors_text():
    return json.dumps(_plain(generate_class_vectors()), indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def _vectors_path():
    return pathlib.Path(__file__).resolve().parent / "vectors" / "class_label.json"


def _write_class_vectors():
    path = _vectors_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(vectors_text())


if __name__ == "__main__":
    if sys.argv[1:] == ["--write"]:
        _write_class_vectors()
    else:
        sys.stderr.write("usage: python -m openddil_labels.rollup_vectors --write\n")
        sys.exit(2)
